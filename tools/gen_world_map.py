#!/usr/bin/env python3
"""Generate web/world-map.js: Natural Earth 110m country boundaries as
pre-projected SVG paths (equirectangular, cropped to lat 85..-60).

Usage: gen_world_map.py [countries.geojson] [out.js]
Default input: /tmp/ne_110m_countries.geojson
  (download: curl -sL -o /tmp/ne_110m_countries.geojson
   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson)
"""
import json
import sys

W, H = 1200, 533
LAT_MAX, LAT_MIN = 85, -60
# Visual center longitude: 105E puts China in the middle of the map.
# The world is still fully shown; the map seam (left/right edge) moves to
# LON_CENTER-180 (i.e. -75, eastern North America).
# Visual center longitude. 150E puts the map seam at -30 (mid-Atlantic,
# east of South America's easternmost point at ~-35W) so no landmass is
# split. China sits left-of-center but stays prominent.
LON_CENTER = 150


def norm_lon(lon):
    lo = LON_CENTER - 180
    return ((lon - lo) % 360) + lo


def px(lon):
    return (norm_lon(lon) - (LON_CENTER - 180)) / 360 * W


def py(lat):
    return (LAT_MAX - lat) / (LAT_MAX - LAT_MIN) * H


def ring_to_path(coords):
    """Closed ring [[lon,lat],...] -> SVG path; split at the map seam
    (LON_CENTER-180) and drop points outside the lat crop."""
    segs, cur, prev_nlon = [], [], None
    for c in coords:
        lon, lat = c[0], c[1]
        if lat > LAT_MAX + 1 or lat < LAT_MIN - 1:
            if len(cur) > 2:
                segs.append(cur)
            cur, prev_nlon = [], None
            continue
        nlon = norm_lon(lon)
        if prev_nlon is not None and abs(nlon - prev_nlon) > 180:
            # crossed the seam: start a new segment
            if len(cur) > 2:
                segs.append(cur)
            cur = []
        cur.append((px(lon), py(lat)))
        prev_nlon = nlon
    if len(cur) > 2:
        segs.append(cur)
    return "".join("M" + "L".join(f"{x:.0f} {y:.0f}" for x, y in s) + "Z" for s in segs)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/tmp/ne_110m_countries.geojson"
    out = sys.argv[2] if len(sys.argv) > 2 else "buildroot-overlay/board/canaan/k230_rockbase/rootfs_overlay/root/web/world-map.js"
    d = json.load(open(src))
    paths = []
    for f in d["features"]:
        if f["properties"].get("ADM0_A3") == "ATA":
            continue  # Antarctica cropped out
        geom = f["geometry"]
        polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
        for poly in polys:
            p = "".join(ring_to_path(ring) for ring in poly)
            if p:
                paths.append(p)
    g = []
    for lon in range(LON_CENTER - 180, LON_CENTER + 181, 30):
        g.append(f"M{px(lon):.0f} 0V{H}")
    for lat in range(LAT_MIN, LAT_MAX + 1, 30):
        if lat in (LAT_MAX, LAT_MIN):
            continue
        g.append(f"M0 {py(lat):.0f}H{W}")
    js = (
        "/* Auto-generated by tools/gen_world_map.py — do not edit.\n"
        " * Natural Earth 110m country boundaries, equirectangular projection,\n"
        " * cropped to lat 85..-60 (Antarctica excluded). Canvas 1200x533.\n"
        " * Visual center at lon " + str(LON_CENTER) + "E (China centered); the map seam\n"
        " * sits at lon " + str(LON_CENTER - 180) + ".\n"
        " * land: one path per country (fill + stroke gives visible borders).\n"
        " * Markers must project with the same lat range (latMax/latMin) and the\n"
        " * same lonCenter (see peerMapProject in app.js). */\n"
        "window.WORLD_MAP = "
        + json.dumps({"w": W, "h": H, "latMax": LAT_MAX, "latMin": LAT_MIN,
                      "lonCenter": LON_CENTER,
                      "land": paths, "graticule": "".join(g)}, separators=(",", ":"))
        + ";\n"
    )
    open(out, "w").write(js)
    print(f"countries={len(paths)} js_bytes={len(js)}")


if __name__ == "__main__":
    main()
